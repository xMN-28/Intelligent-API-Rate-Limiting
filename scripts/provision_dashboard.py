"""Regenerate the committed Grafana dashboard without a Grafana installation."""

import json
from pathlib import Path

PANELS = [
    ("Global admission budget", "irl_rate_budget", "reqps"),
    (
        "Admitted requests by client",
        "sum by (client) (rate(irl_gateway_admitted_total[10s]))",
        "reqps",
    ),
    ("Gateway outcomes", "sum by (outcome) (rate(irl_gateway_requests_total[10s]))", "reqps"),
    (
        "Upstream latency",
        "histogram_quantile(0.95, sum by (le) (rate(irl_upstream_duration_seconds_bucket[10s])))",
        "s",
    ),
    (
        "Admission overhead p95",
        "histogram_quantile(0.95, sum by (le) (rate(irl_admission_duration_seconds_bucket[10s])))",
        "s",
    ),
    ("Gateway in-flight requests", "irl_gateway_inflight", "short"),
    ("Backend worker utilization", "irl_backend_active / irl_backend_workers", "percentunit"),
    ("Backend queue depth", "irl_backend_waiting", "short"),
    ("Backend worker capacity", "irl_backend_workers", "short"),
    (
        "Controller decisions",
        "sum by (reason) (increase(irl_controller_decisions_total[30s]))",
        "short",
    ),
    ("Backend process CPU", "irl_backend_cpu_percent", "percent"),
    ("Backend completed throughput", "rate(irl_backend_completed_total[10s])", "reqps"),
]


def main() -> None:
    panels = []
    for index, (title, expression, unit) in enumerate(PANELS):
        targets = [
            {"refId": "A", "expr": expression, "legendFormat": "{{client}}{{outcome}}{{reason}}"}
        ]
        if title == "Upstream latency":
            targets = [
                {
                    "refId": f"P{q}",
                    "expr": expression.replace("0.95", str(q / 100)),
                    "legendFormat": f"p{q}",
                }
                for q in (50, 95, 99)
            ]
        panels.append(
            {
                "id": index + 1,
                "title": title,
                "type": "timeseries",
                "datasource": {"type": "prometheus", "uid": "prometheus"},
                "gridPos": {"x": (index % 2) * 12, "y": (index // 2) * 8, "w": 12, "h": 8},
                "targets": targets,
                "fieldConfig": {"defaults": {"unit": unit, "min": 0}, "overrides": []},
                "options": {
                    "legend": {"displayMode": "list", "placement": "bottom"},
                    "tooltip": {"mode": "multi"},
                },
            }
        )
    dashboard = {
        "uid": "intelligent-rate-limiting",
        "title": "Intelligent API Rate Limiting",
        "tags": ["admission-control", "experiments"],
        "schemaVersion": 40,
        "version": 1,
        "refresh": "2s",
        "time": {"from": "now-10m", "to": "now"},
        "timezone": "browser",
        "panels": panels,
        "editable": False,
        "description": (
            "Live gateway and backend observations. "
            "Saved experiment comparisons are generated by irl report."
        ),
    }
    path = Path("deploy/grafana/dashboards/gateway.json")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(dashboard, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
