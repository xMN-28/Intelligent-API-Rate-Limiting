"""Regenerate the committed Grafana dashboard without a Grafana installation."""

import json
from pathlib import Path

PANELS = [
    ("Global admission budget", "rlrc_rate_budget", "reqps"),
    (
        "Admitted requests by client",
        "sum by (client) (rate(rlrc_gateway_admitted_total[10s]))",
        "reqps",
    ),
    ("Gateway outcomes", "sum by (outcome) (rate(rlrc_gateway_requests_total[10s]))", "reqps"),
    (
        "Upstream latency",
        "histogram_quantile(0.95, sum by (le) (rate(rlrc_upstream_duration_seconds_bucket[10s])))",
        "s",
    ),
    (
        "Admission overhead p95",
        "histogram_quantile(0.95, sum by (le) (rate(rlrc_admission_duration_seconds_bucket[10s])))",
        "s",
    ),
    ("Gateway in-flight requests", "rlrc_gateway_inflight", "short"),
    ("Backend worker utilization", "rlrc_backend_active / rlrc_backend_workers", "percentunit"),
    ("Backend queue depth", "rlrc_backend_waiting", "short"),
    ("Backend worker capacity", "rlrc_backend_workers", "short"),
    (
        "Controller decisions",
        "sum by (reason) (increase(rlrc_controller_decisions_total[30s]))",
        "short",
    ),
    ("Backend process CPU", "rlrc_backend_cpu_percent", "percent"),
    ("Backend completed throughput", "rate(rlrc_backend_completed_total[10s])", "reqps"),
    ("Offered gateway traffic", "sum(rate(rlrc_gateway_offered_total[10s]))", "reqps"),
    ("Proposed learned budget", "rlrc_proposed_budget", "reqps"),
    (
        "Controller inference p95",
        "histogram_quantile(0.95, sum by (le) "
        "(rate(rlrc_controller_inference_seconds_bucket[10s])))",
        "s",
    ),
    (
        "Safety interventions",
        "sum by (reason) "
        '(increase(rlrc_safety_interventions_total{reason!~"model|fallback"}[30s]))',
        "short",
    ),
    ("Explicit model fallbacks", "increase(rlrc_model_fallbacks_total[30s])", "short"),
    ("Model loaded successfully", "rlrc_model_ready", "short"),
]


def main() -> None:
    panels = []
    for index, (title, expression, unit) in enumerate(PANELS):
        targets = [
            {"refId": "A", "expr": expression, "legendFormat": "{{client}}{{outcome}}{{reason}}"}
        ]
        if title == "Upstream latency":
            targets = [
                {
                    "refId": f"P{q}",
                    "expr": expression.replace("0.95", str(q / 100)),
                    "legendFormat": f"p{q}",
                }
                for q in (50, 95, 99)
            ]
        panels.append(
            {
                "id": index + 1,
                "title": title,
                "type": "timeseries",
                "datasource": {"type": "prometheus", "uid": "prometheus"},
                "gridPos": {"x": (index % 2) * 12, "y": (index // 2) * 8, "w": 12, "h": 8},
                "targets": targets,
                "fieldConfig": {"defaults": {"unit": unit, "min": 0}, "overrides": []},
                "options": {
                    "legend": {"displayMode": "list", "placement": "bottom"},
                    "tooltip": {"mode": "multi"},
                },
            }
        )
    dashboard = {
        "uid": "reinforcement-learning-based-api-rate-control",
        "title": "Reinforcement Learning-Based API Rate Control",
        "tags": ["admission-control", "experiments"],
        "schemaVersion": 40,
        "version": 1,
        "refresh": "2s",
        "time": {"from": "now-10m", "to": "now"},
        "timezone": "browser",
        "panels": panels,
        "editable": False,
        "description": (
            "Live gateway and backend observations. "
            "Saved experiment comparisons are generated by rlrc report."
        ),
    }
    path = Path("deploy/grafana/dashboards/gateway.json")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(dashboard, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
